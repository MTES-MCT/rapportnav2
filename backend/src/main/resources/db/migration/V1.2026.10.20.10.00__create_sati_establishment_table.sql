$$
BEGIN
CREATE TABLE IF NOT EXISTS sati_establishment
(
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sati_id             UUID        NOT NULL REFERENCES sati (id) ON DELETE CASCADE,
  type                VARCHAR(50),
  sub_type            VARCHAR(50),
